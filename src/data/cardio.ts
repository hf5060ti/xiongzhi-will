/** 有氧消耗公式（全站统一） */
export const CARDIO_FORMULA = 'kcal = MET × 体重(kg) × 时长(h)';

export interface CardioMetRow {
  id: string;
  /** 档位名，如「慢走」「中速」 */
  label: string;
  /** 配速 / 强度描述，如「3.2 km/h」 */
  speed: string;
  /** MET 值 */
  met: number;
  /** 体感说明 */
  note: string;
}

export interface ICardioItem {
  id: string;
  name: string;
  en: string;
  icon: LucideIcon;
  tagline: string;
  desc: string;
  /** 档位表：配速 / 强度 → MET */
  metRows: CardioMetRow[];
  /** 优点 */
  pros: string[];
  /** 缺点 / 局限 */
  cons: string[];
  /** 适合人群 */
  suitable: string;
  /** 注意事项 / 实用建议 */
  cautions: string[];
}

/** 参考体重（用于展示「参考 kcal/小时」，实际消耗按用户输入体重实时换算） */
export const CARDIO_REF_WEIGHT = 70;

/** 某项目 MET 区间 → 70kg 参考 kcal/小时 区间文字 */
export function cardioMetRangeText(rows: CardioMetRow[]): string {
  if (!rows.length) return '';
  const mets = rows.map((r) => r.met);
  const min = Math.min(...mets);
  const max = Math.max(...mets);
  const kcal = (m: number) => Math.round(m * CARDIO_REF_WEIGHT);
  return min === max
    ? `${min} MET · 约 ${kcal(min)} kcal/小时（${CARDIO_REF_WEIGHT}kg）`
    : `${min}–${max} MET · 约 ${kcal(min)}–${kcal(max)} kcal/小时（${CARDIO_REF_WEIGHT}kg）`;
}

