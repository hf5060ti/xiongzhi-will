/** 总次数 → 估算时长（分钟）：时长 = 总次数 ÷ 节奏(次/分) */
export function bodyweightMinutes(reps: number, rpm: number): number {
  return reps / rpm;
}

/** 自重动作消耗：kcal = MET × 体重(kg) × 时长(h)，时长由次数与节奏换算 */
export function bodyweightKcal(met: number, weightKg: number, reps: number, rpm: number): number {
  return met * weightKg * (reps / rpm / 60);
}

/** 单次消耗：kcal/次 = MET × 体重(kg) ÷ 节奏(次/分) ÷ 60 */
export function bodyweightKcalPerRep(met: number, weightKg: number, rpm: number): number {
  return (met * weightKg) / (rpm * 60);
}
