/** 条目是否适用于某套方案：relatedDiets 缺省视为通用 */
export function knowledgeMatchesDiet(entry: KnowledgeEntry, dietId: string): boolean {
  return !entry.relatedDiets || entry.relatedDiets.includes(dietId);
}

/** 某套方案可用的讲解条数，供方案详情页入口展示 */
export function knowledgeCountForDiet(dietId: string): number {
  return DIET_KNOWLEDGE.filter((e) => knowledgeMatchesDiet(e, dietId)).length;
}
