/** 一家门店的招牌餐合计（用于「已选 N 家」的汇总展示） */
export function storeTotal(store: TakeoutStore) {
  return store.dishes.reduce(
    (acc, d) => ({
      kcal: acc.kcal + d.kcal,
      protein: acc.protein + d.protein,
      fat: acc.fat + d.fat,
      carb: acc.carb + d.carb,
    }),
    { kcal: 0, protein: 0, fat: 0, carb: 0 },
  );
}
