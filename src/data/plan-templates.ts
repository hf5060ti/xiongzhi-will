/** 单个动作块：中文动作名 + 组次 + 可选要点 */
export interface IPlanTemplateBlock {
  /** 中文动作名（与动作百科一致，可检索） */
  name: string;
  /** 组次，如 "3 × 12/10/8"、"4 × 6-8"、"5 × 5"、"30s 跳 + 30s 休 × 10" */
  set: string;
  /** 动作要点 / 该动作在计划中的位置 */
  note?: string;
}

/** 每周安排中的一天 */
export interface IPlanTemplateDay {
  /** 如 周一 / 休息 */
  day: string;
  /** 训练主题，如 全身 A / 推日 / 休息 */
  focus: string;
  /** 当天内容简述 */
  detail: string;
}

export interface IPlanTemplate {
  id: string;
  /** 中文计划名 */
  name: string;
  /** 英文 / 体系名 */
  en: string;
  /** 一句话定位 */
  tagline: string;
  /** 适合人群 */
  audience: string;
  /** 分组：入门 / 增肌 / 力量 / 减脂 / 场景，用于列表筛选 */
  group: string;
  /** 每周频率 / 单次时长 */
  frequency: string;
  /** 分化说明 */
  split: string;
  /** 每周安排 */
  weekly: IPlanTemplateDay[];
  /** 动作清单（8-15 个） */
  blocks: IPlanTemplateBlock[];
  /** 执行要点 3-6 条 */
  points: string[];
  /** 进阶法则 2-4 条 */
  progression: string[];
  /** 来源标注 */
  source: string;
}

